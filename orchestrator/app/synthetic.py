def _format(template: str, spec: dict[str, Any]) -> str:
    """Naive format helper that swallows missing keys."""
    try:
        return template.format(**spec, move_date_plus_45="early July")
    except KeyError as e:
        log.warning("synthetic template missing key %s; substituting placeholder", e)
        return template.format_map({**spec, "move_date_plus_45": "early July", str(e).strip("'"): "<unknown>"})


async def run_synthetic_specialist(persona: Persona, event_id: str, spec: dict[str, Any]) -> None:
    """Run a 4-turn synthetic conversation for one specialist.

    Turn shape:
      1. Agent (us): opening line per category
      2. Counterparty: opener question
      3. Agent: answer with spec details
      4. Counterparty: confirm with reference number
      (optional) 5. Agent: final bid line

    Each agent turn goes through real PAVO routing. Each counterparty turn is
    pre-templated but emitted to the dashboard so the wall feels alive.
    """
    event = state.events.get(event_id)
    if event is None:
        return

    ctx = event.specialist_calls.get(persona.agent_id)
    if ctx is None:
        return

    cat = persona.category
    if cat not in AGENT_OPENERS:
        log.warning("synthetic mode: no template for category %s", cat)
        return

    # Transition: dispatched → calling → in-progress
    for new_state in ("calling", "in-progress"):
        ctx.state = new_state
        await ws_broker.broadcast({
            "type": "agent_state", "event_id": event_id,
            "agent_id": persona.agent_id, "state": new_state,
            "ts": time.time(),
        })
        await asyncio.sleep(0.4)

    counterparty_lines = [
        COUNTERPARTY_OPENERS[cat],
        *COUNTERPARTY_TURN_TEMPLATES[cat],
    ]

    # Pace the 4 agent turns + 4 counterparty turns across roughly 35 seconds.
    for turn_idx in range(4):
        # Counterparty turn (template fill).
        counterparty_text = _format(counterparty_lines[turn_idx], spec)
        ctx.turn_count += 1
        ctx.transcript.append({"role": "counterparty", "text": counterparty_text, "ts": time.time()})
        await ws_broker.broadcast({
            "type": "transcript_turn", "event_id": event_id, "agent_id": persona.agent_id,
            "turn": ctx.turn_count, "role": "counterparty", "text": counterparty_text, "ts": time.time(),
        })
        await asyncio.sleep(1.2 + 0.3 * turn_idx)

        # Agent turn (real PAVO call).
        if turn_idx == 0:
            user_input = AGENT_OPENERS[cat]
            agent_msg = _format(user_input, spec)
            # Skip PAVO for the opener — it's pre-scripted to keep latency tight.
            tier = "gemma-local"
            cost_cents = 0.0005
            decision_reason = "synthetic opener (pre-scripted)"
        else:
            messages = [
                {"role": "system", "content": persona.system_prompt},
                {"role": "user", "content": counterparty_text},
            ]
            reply = await pavo_chat(messages, role_hint=persona.role_hint, max_tokens=120)
            agent_msg = reply.content
            tier = reply.tier
            cost_cents = reply.cost_cents
            decision_reason = reply.decision_reason

            # Update cost ticker on each real PAVO call.
            event.pavo_cents_total += cost_cents
            event.baseline_cents_total += cost_cents * 4  # rough cloud baseline ratio per paper
            await ws_broker.broadcast({
                "type": "routing_decision", "event_id": event_id, "agent_id": persona.agent_id,
                "turn": ctx.turn_count + 1, "tier": tier, "reason": decision_reason,
                "complexity": 0.0, "ts": time.time(),
            })
            await ws_broker.broadcast({
                "type": "cost_update", "event_id": event_id,
                "pavo_cents": event.pavo_cents_total, "baseline_cents": event.baseline_cents_total,
                "ts": time.time(),
            })

        ctx.turn_count += 1
        ctx.transcript.append({"role": "agent", "text": agent_msg, "pavo_tier": tier, "ts": time.time()})
        await ws_broker.broadcast({
            "type": "transcript_turn", "event_id": event_id, "agent_id": persona.agent_id,
            "turn": ctx.turn_count, "role": "agent", "text": agent_msg,
            "pavo_tier": tier, "ts": time.time(),
        })
        await asyncio.sleep(0.8 + 0.2 * turn_idx)

    # Final state: closed
    ctx.state = "closed"
    ctx.closed_at = time.time()
    ctx.bid = {"synthetic": True, "category": cat}
    await ws_broker.broadcast({
        "type": "agent_state", "event_id": event_id, "agent_id": persona.agent_id,
        "state": "closed", "ts": time.time(),
    })


async def run_synthetic_fan_out(event_id: str, spec: dict[str, Any], specialists: list[Persona]) -> None:
    """Run synthetic conversations for all specialists in parallel."""
    # Default missing spec fields so templates render.
    spec_filled = {
        "user_name": "the customer",
        "origin_address": spec.get("origin_address", "the SF address"),
        "destination_address": spec.get("destination_address", "the Austin address"),
        "move_date": spec.get("move_date", "May 31"),
        **spec,
    }
    await asyncio.gather(*[run_synthetic_specialist(p, event_id, spec_filled) for p in specialists])

    # Event complete: trigger the same post-completion sponsor fan-out as the real flow.
    # (Imported here to avoid circular import at module load.)
    from .main import _fire_event_complete_sponsors
    await _fire_event_complete_sponsors(event_id)
