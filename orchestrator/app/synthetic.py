"""Synthetic-demo mode — runs realistic 4-turn fake conversations per specialist
via PAVO directly, without AgentPhone.

Use cases:
  1. Rehearsal: run the full demo flow without needing AgentPhone API keys.
  2. Backup video: record a clean 90-second demo for the worst-case scenario
     where AgentPhone fails on stage.
  3. Pre-stage testing: verify the dashboard + PAVO + cost ticker without
     waiting for real outbound calls to connect.

Architecture:
  - Each specialist runs a 4-turn conversation in-process (no AgentPhone, no webhook)
  - Both sides of the conversation are generated by PAVO via separate role_hints
  - Real PAVO routing decisions fire (the routing layer is genuinely exercised)
  - Real cost is accumulated (gemma-local turns ~0.005c each; gemini-flash 18%; opus 2%)
  - All WebSocket events flow normally to the dashboard

The synthetic counterparty turns use a different role_hint ("counterparty-{category}")
so PAVO can still classify them appropriately. For the demo, this is real PAVO
routing — only the AgentPhone leg is skipped.
"""
